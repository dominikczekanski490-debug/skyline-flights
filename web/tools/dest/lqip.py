"""Regenerate src/destlqip.ts: a tiny 20x15 (4:3, same shape as the heroes) WebP preview of every bundled destination photo,
shown blurred (background-size: cover) until the real photo arrives. Run from anywhere after the photos in public/dest change."""
import json,os,base64,io
from PIL import Image
H=os.path.dirname(os.path.abspath(__file__)); D=f"{H}/../../public/dest"
idx=json.load(open(f"{D}/index.json")); out={}
for k,v in sorted(idx.items()):
  if not v.get("img") or not os.path.exists(f"{D}/{k}.webp"): continue
  im=Image.open(f"{D}/{k}.webp").convert("RGB").resize((20,15),Image.BOX); b=io.BytesIO(); im.save(b,"WEBP",quality=40,method=6)
  out[k]=base64.b64encode(b.getvalue()).decode()
open(f"{H}/../../src/destlqip.ts","w").write("// Tiny 20×15 WebP previews of each bundled destination photo (public/dest), shown blurred until the real photo arrives. Generated by tools/dest/lqip.py from the bundled images.\nexport const LQIP: Record<string, string> = "+json.dumps(out,separators=(",",":"))+";\n")
print(len(out),"previews",sum(len(x) for x in out.values())//1024,"KB")

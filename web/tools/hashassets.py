#!/usr/bin/env python3
"""Give cache-sensitive static assets content-hashed names so no browser / service-worker cache can serve a stale copy.
Run from web/: renames public/liveries/fins/<CODE>.webp -> <CODE>-<hash>.webp, copies public/dest/index.json -> index-<hash>.json,
and writes src/assets.gen.ts (TAIL_FILES map + DEST_INDEX path). Re-run after changing any fin or index.json."""
import hashlib,os,re,glob,shutil
H=lambda p: hashlib.sha256(open(p,"rb").read()).hexdigest()[:8]
F="public/liveries/fins"; tails={}; att=open(f"{F}/ATTRIBUTION.md").read()
for p in sorted(glob.glob(f"{F}/*.webp")):
  b=os.path.basename(p); k=re.match(r"([A-Z0-9]{2})",b).group(1); n=f"{k}-{H(p)}.webp"
  if b!=n: os.rename(p,f"{F}/{n}")
  att=re.sub(r"\| %s(-[0-9a-f]{8})?\.webp \|"%k,f"| {n} |",att); tails[k]=f"/liveries/fins/{n}"
open(f"{F}/ATTRIBUTION.md","w").write(att)
wl={}
for p in sorted(glob.glob("public/logos/w/*.png")):
  b=os.path.basename(p); m=re.match(r"([A-Z0-9]{2})(-[0-9a-f]{8})?\.png$",b); k=m.group(1); n=f"{k}-{H(p)}.png"
  if b!=n: os.rename(p,f"public/logos/w/{n}")
  wl[k]=f"/logos/w/{n}"
for p in glob.glob("public/dest/index-*.json"): os.remove(p)
di=f"index-{H('public/dest/index.json')}.json"; shutil.copy("public/dest/index.json",f"public/dest/{di}")
open("src/assets.gen.ts","w").write("// generated by tools/hashassets.py — content-hashed asset names (never stale in any cache)\nexport const TAIL_FILES: Record<string, string> = "+repr(tails).replace("'",'"')+";\nexport const WHITE_LOGOS: Record<string, string> = "+repr(wl).replace("'",'"')+";\nexport const DEST_INDEX = \"/dest/"+di+"\";\n")
print(len(tails),di)
